import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {resolve} from 'node:path';
import {setTimeout as delay} from 'node:timers/promises';
const server=spawn(process.execPath,[resolve('node_modules/vite/bin/vite.js'),'preview','--host','127.0.0.1','--port','4175','--strictPort'],{stdio:'ignore'});
let browser;
try{
 for(let i=0;i<50;i++){try{if((await fetch('http://127.0.0.1:4175')).ok)break}catch{}await delay(200)}
 browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[],google=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/google-analytics|googletagmanager/.test(r.url()))google.push(r.url())});
 await page.goto('http://127.0.0.1:4175/?analytics_debug=1&utm_source=threads&utm_campaign=launch&sync_key=must-not-leak');
 await page.locator('.starter-card').first().waitFor();
 assert.equal(await page.locator('.starter-card').count(),3);
 assert.equal(await page.locator('.home-pick').count(),12);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'/tmp/storysteps-launch-home.png',fullPage:false});
 await page.locator('.starter-card').nth(1).click();
 await page.locator('.prose').waitFor();
 assert.match(page.url(),/chapter=import-rain-bell-1/);
 assert.equal(await page.locator('.reader-settings').getAttribute('open'),null);
 assert.equal(await page.locator('.reader-toc').isVisible(),false);
 assert.equal(await page.locator('.mobile-nav').isVisible(),false);
 const word=page.locator('.prose .inline-word').filter({hasText:/^bell$/}).first();
 await word.scrollIntoViewIfNeeded();await word.click();
 await page.locator('.word-dock').waitFor();
 const position=await page.evaluate(()=>scrollY);
 await page.getByRole('button',{name:'返回原文',exact:true}).click();
 assert(Math.abs((await page.evaluate(()=>scrollY))-position)<3,'Lookup must not move reading position');
 await page.locator('.chapter-pagination').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>JSON.parse(sessionStorage.getItem('storysteps-analytics-debug')||'[]').some(e=>e.event==='chapter_end'));
 await page.locator('.chapter-pagination').getByRole('button',{name:'下一章'}).click();
 await page.waitForFunction(()=>document.querySelector('.reader-chapter-number')?.textContent?.includes('第 2 章'));
 await page.locator('.prose').waitFor();
 await page.reload();await page.locator('.prose').waitFor();
 assert.match(await page.locator('.reader-chapter-number').textContent(),/第 2 章/);
 const events=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('storysteps-analytics-debug')||'[]'));
 for(const name of ['visit','chapter_start','word_lookup','chapter_end','next_chapter'])assert(events.some(e=>e.event===name),name);
 assert(events.every(e=>e.source==='threads'&&e.campaign==='launch'));
 assert(!JSON.stringify(events).includes('must-not-leak'));
 assert.equal(google.length,0,'No Google requests before configuration and consent');
 await page.locator('.header .brand').click();
 assert(!new URL(page.url()).searchParams.has('chapter'));
 await page.reload();await page.locator('.starter-card').first().waitFor();
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PASS: three picks, direct links/reload, mobile reader, stable lookup, event funnel, attribution, no unconsented Google requests');
}finally{await browser?.close();server.kill()}
