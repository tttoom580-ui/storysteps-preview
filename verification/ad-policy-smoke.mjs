import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {blockForChapter,appendGrant} from '../app/access-policy.mjs';

const rewarded=JSON.parse(readFileSync('public/rewarded-config.json','utf8'));
const display=JSON.parse(readFileSync('public/display-ad-config.json','utf8'));
const index=readFileSync('index.html','utf8');
const builder=readFileSync('scripts/build_public_pages.py','utf8');
assert.equal(rewarded.enabled,false,'No verified rewarded ad unit; must stay off');
assert.equal(rewarded.adUnitPath,'','Do not invent an ad unit');
assert.equal(rewarded.allowFreeFallback,true,'Free access always available');
assert.equal(display.enabled,false,'No approved display slot; must stay off');
assert.equal(display.slot,'','Do not invent an ad slot');
assert(!index.includes('src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js'),'Do not pre-load Google ads before opt in');
assert(builder.includes('ADS_ENABLED=False'),'Static pages must not pre-load ad scripts');
assert.equal(blockForChapter(1),null);
assert.deepEqual(blockForChapter(6),{start:6,end:9});
assert.deepEqual(blockForChapter(9),{start:6,end:9});
assert.deepEqual(blockForChapter(10),{start:10,end:13});
assert.deepEqual(blockForChapter(25),{start:22,end:25});
let grants=appendGrant([],'tomorrow',6,'launch-gift',1000);
assert.equal(grants.length,1);
grants=appendGrant(grants,'tomorrow',7,'launch-gift',1000);
assert.equal(grants.length,1,'A repeated unlock must not be appended');
grants=appendGrant(grants,'tomorrow',6,'rewarded-ad',1000);
assert.equal(grants.length,1,'Reward callback cannot add duplicate grant for same block');
grants=appendGrant(grants,'tomorrow',10,'launch-gift',1000);
assert.equal(grants.length,2);
assert.throws(()=>appendGrant(grants,'tomorrow',5,'rewarded-ad'));
console.log('PASS: no unapproved ad scripts, ad configs fail closed, 5+4 chapter policy and idempotent unlock grants');
